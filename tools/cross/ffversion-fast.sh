#!/bin/sh
# FFmpeg ffbuild/version.sh yerine geçen proot-güvenli sarıcı:
# orijinali `... | tail -1` boru hattında kesilen oturumlarda 90+ dk asılı
# kalabilir (kanıt ffm64: make tek dosyada 1:33:08 bekledi). Sabit sürüm
# yazar; kullanım: <bu dosya> <src_root> <ffversion.h çıkış yolu>
SRC="$1"
OUT="$2"
[ -n "$OUT" ] || { echo "ffversion-fast: çıkış yolu yok" >&2; exit 1; }
{
  printf '/* Automatically generated by ffversion-fast (build-ffmpeg.sh). Do not edit. */\n'
  printf '#ifndef AVUTIL_FFVERSION_H\n'
  printf '#define AVUTIL_FFVERSION_H\n'
  printf '#define FFMPEG_VERSION "6.1.2"\n'
  printf '#endif\n'
} > "$OUT" || { echo "ffversion-fast: $OUT yazilamadi" >&2; exit 1; }
exit 0
